func installTracing(t *testing.T, provider *sdktrace.TracerProvider) {
	t.Helper()
	previous := otel.GetTracerProvider()
	otel.SetTracerProvider(provider)
	t.Cleanup(func() {
		if err := provider.Shutdown(context.Background()); err != nil {
			t.Error(err)
		}
		otel.SetTracerProvider(previous)
	})
}

// An SDK exporter sends the spans generated by a workload batch back through the
// same HTTP ingest service. The system-authenticated export must end the chain.
func TestProxyTraceLoopbackStopsAtSystemIngestion(t *testing.T) {
	for _, protocol := range []string{"http", "grpc"} {
		for _, authentication := range []string{"system-token", "worker-token"} {
			t.Run(protocol+"/"+authentication, func(t *testing.T) {
				service, _, cp := newTestService(t, nil)
				var mu sync.Mutex
				var stored ptrace.Traces
				traces, err := consumer.NewTraces(func(_ context.Context, payload ptrace.Traces) error {
					mu.Lock()
					defer mu.Unlock()
					stored = ptrace.NewTraces()
					payload.CopyTo(stored)
					return nil
				})
				if err != nil {
					t.Fatal(err)
				}
				service.consumers.Traces = traces
				var exports atomic.Int32
				var marked atomic.Bool
				handler := service.Handler()
				server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
					if r.URL.Path == TracesPath {
						if exports.Add(1) > 2 {
							http.Error(w, "recursive export", http.StatusServiceUnavailable)
							return
						}
						body, readErr := io.ReadAll(r.Body)
						if readErr != nil {
							t.Errorf("read self export: %v", readErr)
							w.WriteHeader(http.StatusInternalServerError)
							return
						}
						payload := ptraceotlp.NewExportRequest()
						if decodeErr := payload.UnmarshalProto(body); decodeErr != nil {
							t.Errorf("decode self export: %v", decodeErr)
							w.WriteHeader(http.StatusBadRequest)
							return
						}
						value, _ := payload.Traces().
							ResourceSpans().
							At(0).
							Resource().
							Attributes().
							Get(systemtenant.ScopeAttribute)
						marked.Store(value.Str() == systemtenant.PlatformScope)
						r.Body = io.NopCloser(bytes.NewReader(body))
					}
					handler.ServeHTTP(w, r)
				}))
				t.Cleanup(server.Close)
				auth := bearer.Header(testSystemToken)
				clusterID := systemtenant.ControlPlaneClusterID
				if authentication == "worker-token" {
					auth = cp.bearer()
					clusterID = testClusterID
				}
				t.Setenv("OTEL_EXPORTER_OTLP_TRACES_ENDPOINT", server.URL+TracesPath)
				t.Setenv("OTEL_EXPORTER_OTLP_TRACES_HEADERS", "Authorization="+strings.ReplaceAll(auth, " ", "%20"))
				// A user-provided resource setting cannot erase the recursion guard.
				t.Setenv("OTEL_RESOURCE_ATTRIBUTES", "loco.telemetry.scope=workload")
				previous := otel.GetTracerProvider()
				provider, err := otelsetup.Start(t.Context(), "loco-obs-proxy", "test")
				if err != nil {
					t.Fatal(err)
				}
				t.Cleanup(func() {
					if err := provider.Shutdown(context.Background()); err != nil {
						t.Error(err)
					}
					otel.SetTracerProvider(previous)
				})
				if protocol == "grpc" {
					if _, err := grpcClient(t, service).Export(grpcAuthorized(t, cp), testLogsRequest()); err != nil {
						t.Fatal(err)
					}
				} else {
					request, err := http.NewRequestWithContext(
						t.Context(),
						http.MethodPost,
						server.URL+LogsPath,
						bytes.NewReader(protoBody(t)),
					)
					if err != nil {
						t.Fatal(err)
					}
					request.Header.Set("Authorization", cp.bearer())
					request.Header.Set("Content-Type", protobufContentType)
					request.Header.Set("Traceparent", "00-11111111111111111111111111111111-2222222222222222-01")
					response, err := server.Client().Do(request)
					if err != nil {
						t.Fatal(err)
					}
					defer response.Body.Close()
					if response.StatusCode != http.StatusOK {
						t.Fatalf("ingest status = %d", response.StatusCode)
					}
				}
				// A second flush would export another generation if self ingestion made a span.
				for range 2 {
					if err := provider.ForceFlush(t.Context()); err != nil {
						t.Fatal(err)
					}
				}
				if got := exports.Load(); got != 1 {
					t.Fatalf("self exports = %d, want exactly one", got)
				}
				if !marked.Load() {
					t.Fatal("exported proxy span lacks platform scope before ingest classification")
				}
				mu.Lock()
				defer mu.Unlock()
				if stored.SpanCount() != 1 {
					t.Fatalf("stored self spans = %d, want one", stored.SpanCount())
				}
				spans := stored.ResourceSpans().At(0)
				requireSystemTenant(t, spans.Resource(), clusterID)
				span := spans.ScopeSpans().At(0).Spans().At(0)
				if span.Name() != "ingest.logs" || !span.ParentSpanID().IsEmpty() {
					t.Fatalf("self span = %q parent %s, want root ingest.logs", span.Name(), span.ParentSpanID())
				}
			})
		}
	}
}

func TestOnlyAcceptedWorkloadBatchesProduceSpans(t *testing.T) {
	now := time.Now()
	for _, test := range []struct {
		name                      string
		token                     string
		platform, mixed, rejected bool
		want                      int
	}{
		{name: "workload", want: 3},
		{name: "control plane", token: testSystemToken, want: 0},
		{name: "worker platform", platform: true, want: 0},
		{name: "mixed workload and platform", mixed: true, want: 3},
		{name: "only rejected workloads", rejected: true, want: 0},
		{name: "rejected workload and accepted platform", mixed: true, rejected: true, want: 0},
	} {
		t.Run(test.name, func(t *testing.T) {
			recorder := tracetest.NewSpanRecorder()
			installTracing(t, sdktrace.NewTracerProvider(sdktrace.WithSpanProcessor(recorder)))
			service, _, cp := newTestService(t, nil)
			auth := cp.bearer()
			if test.token != "" {
				auth = bearer.Header(test.token)
			}
			admission, err := service.gate.Admit(t.Context(), auth)
			if err != nil {
				t.Fatal(err)
			}
			logs, traces, metrics := testLogs(now), testTraces(now), testMetrics(now)
			if test.platform {
				logs, traces, metrics = platformLogs(now, ""), platformTraces(now, ""), platformMetrics(now, "")
			}
			if test.mixed {
				platformLogs(now, "").ResourceLogs().At(0).CopyTo(logs.ResourceLogs().AppendEmpty())
				platformTraces(now, "").ResourceSpans().At(0).CopyTo(traces.ResourceSpans().AppendEmpty())
				platformMetrics(now, "").ResourceMetrics().At(0).CopyTo(metrics.ResourceMetrics().AppendEmpty())
			}
			if test.rejected {
				logs.ResourceLogs().At(0).Resource().Attributes().PutStr(workspaceAttribute, testNeverPlacedID)
				traces.ResourceSpans().At(0).Resource().Attributes().PutStr(workspaceAttribute, testNeverPlacedID)
				metrics.ResourceMetrics().At(0).Resource().Attributes().PutStr(workspaceAttribute, testNeverPlacedID)
			}
			if _, err := export(
				t.Context(), service, service.logsSignal(), admission,
				plogotlp.NewExportRequestFromLogs(logs),
			); err != nil {
				t.Fatal(err)
			}
			if _, err := export(
				t.Context(), service, service.tracesSignal(), admission,
				ptraceotlp.NewExportRequestFromTraces(traces),
			); err != nil {
				t.Fatal(err)
			}
			if _, err := export(
				t.Context(), service, service.metricsSignal(), admission,
				pmetricotlp.NewExportRequestFromMetrics(metrics),
			); err != nil {
				t.Fatal(err)
			}
			if got := len(recorder.Ended()); got != test.want {
				t.Fatalf("recorded %d spans, want %d", got, test.want)
			}
		})
	}
}

func TestGRPCSystemAndPlatformLogsDoNotProduceSpans(t *testing.T) {
	for _, sender := range []string{"control-plane", "worker-platform"} {
		t.Run(sender, func(t *testing.T) {
			recorder := tracetest.NewSpanRecorder()
			installTracing(t, sdktrace.NewTracerProvider(sdktrace.WithSpanProcessor(recorder)))
			service, _, cp := newTestService(t, nil)
			ctx := grpcAuthorized(t, cp)
			request := testLogsRequest()
			if sender == "control-plane" {
				ctx = metadata.NewOutgoingContext(
					t.Context(),
					metadata.Pairs(authorizationMetadata, bearer.Header(testSystemToken)),
				)
			} else {
				request = plogotlp.NewExportRequestFromLogs(platformLogs(time.Now(), ""))
			}
			if _, err := grpcClient(t, service).Export(ctx, request); err != nil {
				t.Fatal(err)
			}
			if got := len(recorder.Ended()); got != 0 {
				t.Fatalf("%s ingest recorded %d spans", sender, got)
			}
		})
	}
}

func TestIngestStorageFailureIsRecordedOnWorkloadSpan(t *testing.T) {
	recorder := tracetest.NewSpanRecorder()
	installTracing(t, sdktrace.NewTracerProvider(sdktrace.WithSpanProcessor(recorder)))
	service, _, cp := newTestService(t, errStorageDown)
	response := post(t, service, cp.bearer(), protobufContentType, "", protoBody(t))
	if response.Code != http.StatusServiceUnavailable {
		t.Fatalf("status = %d, want 503", response.Code)
	}
	spans := recorder.Ended()
	if len(spans) != 1 {
		t.Fatalf("spans = %d, want one", len(spans))
	}
	if spans[0].Status().Code != codes.Error || len(spans[0].Events()) != 1 {
		t.Fatalf("span status = %v, events = %v", spans[0].Status(), spans[0].Events())
	}
}
